function thickStar(x: number, y: number) {
  const cx = x + 0.5;
  const cy = y + 0.5;
  const outerR = 0.45;
  const innerR = 0.2;
  const spikes = 5;
  let path = `M ${cx} ${cy - outerR}`;
  for (let i = 0; i < spikes; i++) {
    const outerAngle = (Math.PI * 2 * i) / spikes - Math.PI / 2;
    const innerAngle = outerAngle + Math.PI / spikes;
    const ox = cx + Math.cos(outerAngle) * outerR;
    const oy = cy + Math.sin(outerAngle) * outerR;
    const ix = cx + Math.cos(innerAngle) * innerR;
    const iy = cy + Math.sin(innerAngle) * innerR;
    path += ` L ${ox} ${oy} L ${ix} ${iy}`;
  }
  path += " Z";
  return path;
}

